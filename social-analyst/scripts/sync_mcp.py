#!/usr/bin/env python3
"""Generate .codex/config.toml and .grok/config.toml from .mcp.json (the source of truth).

Bearer headers written as "Bearer ${VAR}" become `bearer_token_env_var = "VAR"`, so no secret is
ever written to disk. Run after editing .mcp.json:  python scripts/sync_mcp.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
servers = json.loads((ROOT / ".mcp.json").read_text())["mcpServers"]


def q(s: str) -> str:
    return json.dumps(s)


lines = ["# GENERATED by scripts/sync_mcp.py from .mcp.json — edit that file, not this one.", ""]
for name, s in servers.items():
    lines.append(f"[mcp_servers.{name}]")
    if "url" in s:
        lines.append(f"url = {q(s['url'])}")
        auth = (s.get("headers") or {}).get("Authorization", "")
        if m := re.fullmatch(r"Bearer \$\{(\w+)(?::-[^}]*)?\}", auth):
            lines.append(f"bearer_token_env_var = {q(m.group(1))}")
    else:
        lines.append(f"command = {q(s['command'])}")
        lines.append("args = [" + ", ".join(q(a) for a in s.get("args", [])) + "]")
        if s.get("env"):
            lines.append("env_vars = [" + ", ".join(q(k) for k in s["env"]) + "]")
    lines.append("")

for d in (".codex", ".grok"):
    (ROOT / d).mkdir(exist_ok=True)
    (ROOT / d / "config.toml").write_text("\n".join(lines))
    print(f"wrote {d}/config.toml ({len(servers)} servers)")
